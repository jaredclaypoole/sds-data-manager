"""File-selection helpers shared by database and API dependency sources."""

import datetime
import logging
from collections.abc import Sequence
from typing import Protocol, TypeVar

import imap_data_access

logger = logging.getLogger(__name__)


class SpinMetadata(Protocol):
    """The spin fields needed to select and order overlapping records."""

    @property
    def start_date(self) -> datetime.datetime:
        """Return the first covered time."""
        ...

    @property
    def end_date(self) -> datetime.datetime:
        """Return the last covered time."""
        ...

    @property
    def version(self) -> str:
        """Return the numeric version string."""
        ...


SpinRecordType = TypeVar("SpinRecordType", bound=SpinMetadata)


# The UTC value below is the instant of the SPICE J2000 (TT) epoch, generated by:
# >>> spiceypy.et2utc(spiceypy.unitim(0, "TT", "ET"), "ISOC", 9)
# '2000-01-01T11:58:55.816000000'
# Computed directly rather than via spiceypy.datetime2et() at call time, since
# that requires a leapseconds kernel to be furnished - this function runs in
# the ephemeral per-job-run compute environment (a fresh container per
# Dagster run), so furnishing the kernel there would mean an S3 and database
# round trip on every single job run just to resolve a SPICE dependency time
# range. Leap seconds added after this epoch (5, as of 2017-01-01) are not
# accounted for, giving a few seconds of residual error - well within the
# tolerance needed to identify which SPICE kernels cover a given time range.
_TTJ2000_EPOCH_UTC = datetime.datetime(
    2000, 1, 1, 11, 58, 55, 816000, tzinfo=datetime.timezone.utc
)


def _seconds_since_j2000(dt: datetime.datetime) -> float:
    """Convert a datetime to SPICE ephemeris time (approx. TDB seconds past J2000).

    Full time-of-day precision is preserved, unlike a `%Y%m%d`-string-based
    conversion, which would round down to day boundaries.

    Parameters
    ----------
    dt : datetime.datetime
        The datetime to convert. Assumed to be UTC if not timezone-aware.

    Returns
    -------
    float
        Approximate SPICE ephemeris time: seconds past the J2000 epoch.
    """
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=datetime.timezone.utc)
    return (dt - _TTJ2000_EPOCH_UTC).total_seconds()


def check_for_missing_kernels(
    combined_kernel_sources: str, metakernel_files: list[str]
) -> list[str]:
    """Check if all requested kernels are present in the metakernel files.

    We need to ensure that the returned list of metakernel files includes
    all requested kernels, especially for ephemeris kernels. The API can
    return the "best" ephemeris kernels, which can include both historical
    and predicted kernels depending on the input time range. If the user
    specifically requests only one ephemeris kernel, e.g. historical
    ephemeris kernels, we must verify that only historical files are
    returned. Otherwise, both historical and predicted kernels are acceptable.

    Additionally, the API can return multiple kernels for the same source
    if the files cover specific date ranges. Because of this, we must
    check that all requested sources are present in the returned
    metakernel files, rather than performing a direct one-to-one
    comparison. Each source may correspond to multiple kernel files.

    Parameters
    ----------
    combined_kernel_sources : str
        Comma-separated string of requested kernel sources.
    metakernel_files : list
        List of metakernel files found.

    Returns
    -------
    list
        Unique list of missing kernels. If empty, all requested kernels were found.
    """
    requested_kernels = set(combined_kernel_sources.split(","))
    expected_ephemeris = set(
        [kernel for kernel in requested_kernels if "ephemeris_" in kernel]
    )
    expected_other_kernels = set(
        [kernel for kernel in requested_kernels if "ephemeris_" not in kernel]
    )

    ephemeris_found = set()
    other_kernels_found = set()
    missing_kernels = set()

    for file in metakernel_files:
        file_obj = imap_data_access.SPICEFilePath(file)
        # Extract the kernel type from the file name
        kernel_type = file_obj.spice_metadata["type"]
        if "ephemeris_" in kernel_type:
            ephemeris_found.add(kernel_type)
        else:
            other_kernels_found.add(kernel_type)

    # Check if all other requested kernels are found
    if expected_other_kernels != other_kernels_found:
        logger.error(
            f"Non-ephemeris kernels {expected_other_kernels} not found in "
            f"metakernel files {other_kernels_found}"
        )
        missing_kernels.update(expected_other_kernels - other_kernels_found)

    # If any single ephemeris kernel is requested, and not found add it to
    # the missing kernels list.
    if (
        len(expected_ephemeris) == 1
        and next(iter(expected_ephemeris)) not in ephemeris_found
    ):
        missing_kernels.update(expected_ephemeris)

    # If 'best' ephemeris kernel is requested, check that at least one of the kernels
    # is found in the metakernel files.
    if len(expected_ephemeris) > 1 and not any(
        "ephemeris_" in kernel for kernel in ephemeris_found
    ):
        missing_kernels.update(expected_ephemeris)

    logger.info(
        f"Requested ephemeris kernels: {expected_ephemeris}, "
        f"found in metakernel files: {ephemeris_found}"
        f"\nRequested other kernels: {expected_other_kernels}, "
        f"found in metakernel files: {other_kernels_found}"
        f"\nMissing kernels: {missing_kernels}"
    )
    return sorted(list(missing_kernels))


def _is_superseded(
    record: SpinMetadata,
    records: Sequence[SpinMetadata],
    start_day: datetime.date,
    end_day: datetime.date,
) -> bool:
    """Check whether higher-version spin files cover a record within a window.

    A spin file is superseded when every day it covers inside the window is
    also covered by a spin file with a higher version. Newer deliveries do not
    always split days the same way as older ones (e.g. ``imap_2025_360_2025_360_01``
    is replaced by ``imap_2025_359_2025_360_10`` and ``imap_2025_360_2025_361_10``),
    so this cannot be decided by matching identical date ranges.

    Parameters
    ----------
    record : Row
        The SpinFiles record to check.
    records : list
        All candidate SpinFiles records overlapping the window.
    start_day : datetime.date
        First day of the window.
    end_day : datetime.date
        Last day of the window.

    Returns
    -------
    bool
        True if the record is fully covered by higher-version records.
    """
    newer_ranges = [
        (other.start_date.date(), other.end_date.date())
        for other in records
        if int(other.version) > int(record.version)
    ]
    if not newer_ranges:
        return False

    day = max(record.start_date.date(), start_day)
    last_day = min(record.end_date.date(), end_day)
    while day <= last_day:
        if not any(start <= day <= end for start, end in newer_ranges):
            return False
        day += datetime.timedelta(days=1)
    return True


def select_spin_records(
    candidates: list[SpinRecordType],
    start_date: datetime.datetime,
    end_date: datetime.datetime,
) -> list[SpinRecordType]:
    """Drop fully superseded records and order the remainder by priority.

    Candidates must be in ingestion order so stable sorting preserves tie breaks.
    """
    start_day = start_date.date()
    end_day = end_date.date()
    records = [
        record
        for record in candidates
        if not _is_superseded(record, candidates, start_day, end_day)
    ]
    # imap_processing gives the last file the highest priority. The sort is
    # stable, so ingestion order breaks ties in version and start date.
    records.sort(key=lambda record: (int(record.version), record.start_date))
    return records
